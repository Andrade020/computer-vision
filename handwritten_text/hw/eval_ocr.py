"""
Evaluate glyph recognizability via OCR instead of pixel distance -- a much
more meaningful proxy for "does this actually look like the intended
character" than raw pixel MSE, which rewards blurry nonsense shapes with low
distance and can penalize a sharp, correct, slightly-shifted glyph.

Compares, per class:
  - REAL ink samples from the bank (the ceiling: how reliable is OCR on
    genuinely good handwriting to begin with -- Tesseract isn't perfect
    even on real cursive samples)
  - NEURAL samples generated by the trained CVAE (hw/checkpoints/best.pt)

then rolls up common-vs-rare-class accuracy to quantify, with numbers instead
of eyeballing, how much worse the network does on classes it saw little/no
real data for. Reports both exact-match and case-insensitive match, since
several Latin letter pairs (C/c, O/o, S/s, P/p, U/u, V/v, W/w, X/x, Z/z) are
just scaled versions of each other -- OCR (and humans) can legitimately get
the case wrong on a perfectly-formed glyph, which isn't a generation failure.

  python -m hw.eval_ocr --n 8
"""
import argparse
import json
import os
import pickle

import numpy as np
from PIL import Image
import pytesseract

from .model import GlyphGenerator, _tight

HERE = os.path.dirname(os.path.abspath(__file__))
TESSERACT_CANDIDATES = [
    r"C:\Program Files\Tesseract-OCR\tesseract.exe",
    r"C:\Program Files (x86)\Tesseract-OCR\tesseract.exe",
]
for _p in TESSERACT_CANDIDATES:
    if os.path.exists(_p):
        pytesseract.pytesseract.tesseract_cmd = _p
        break

WHITELIST = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"


def ocr_char(mask, canvas=140, pad=30):
    """Render a tight glyph mask onto a padded white canvas and OCR it as a
    single character. Returns the recognized character (possibly ''), or ''
    if the mask is empty."""
    mask = np.clip(mask, 0, 1)
    if mask.size == 0 or mask.max() <= 0:
        return ""
    h, w = mask.shape
    scale = (canvas - 2 * pad) / max(h, w)
    nh, nw = max(1, int(round(h * scale))), max(1, int(round(w * scale)))
    g = Image.fromarray(((1 - mask) * 255).astype(np.uint8)).resize(
        (nw, nh), Image.LANCZOS)
    im = Image.new("L", (canvas, canvas), 255)
    im.paste(g, ((canvas - nw) // 2, (canvas - nh) // 2))
    cfg = f"--psm 10 -c tessedit_char_whitelist={WHITELIST}"
    txt = pytesseract.image_to_string(im, config=cfg).strip()
    return txt[:1] if txt else ""


def evaluate(n_per_class=8, seed=0, ckpt="hw/checkpoints/best.pt"):
    with open(os.path.join(HERE, "data", "glyph_bank.pkl"), "rb") as f:
        bank = pickle.load(f)["bank"]
    manifest = json.load(open(os.path.join(HERE, "data", "manifest.json")))
    counts = manifest["per_class_kept"]

    gen = GlyphGenerator(ckpt)
    npr = np.random.RandomState(seed)

    rows = []
    for ch in sorted(bank.keys()):
        n = counts.get(ch, len(bank[ch]))
        real_samples = bank[ch][:n_per_class]
        real_exact = real_ci = 0
        for s in real_samples:
            m = _tight((s.astype(np.float32) / 255.0) > 0.35)
            pred = ocr_char(m)
            real_exact += int(pred == ch)
            real_ci += int(pred.lower() == ch.lower())
        real_exact_acc = real_exact / max(1, len(real_samples))
        real_ci_acc = real_ci / max(1, len(real_samples))

        neu_exact_acc = neu_ci_acc = None
        if ch in gen.cls_to_idx:
            neu_exact = neu_ci = 0
            for _ in range(n_per_class):
                m = gen.generate(ch, npr, temperature=0.7)
                pred = ocr_char(m)
                neu_exact += int(pred == ch)
                neu_ci += int(pred.lower() == ch.lower())
            neu_exact_acc = neu_exact / n_per_class
            neu_ci_acc = neu_ci / n_per_class

        rows.append(dict(ch=ch, n=n, real_exact=real_exact_acc, real_ci=real_ci_acc,
                         neu_exact=neu_exact_acc, neu_ci=neu_ci_acc))
    return rows


def _avg(rows, key):
    vals = [r[key] for r in rows if r[key] is not None]
    return sum(vals) / len(vals) if vals else float("nan")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=8, help="samples per class to test")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--ckpt", default="hw/checkpoints/best.pt")
    ap.add_argument("--json", default=None, help="also dump raw per-class rows here")
    args = ap.parse_args()

    rows = evaluate(n_per_class=args.n, seed=args.seed, ckpt=args.ckpt)
    rows.sort(key=lambda r: r["n"])

    if args.json:
        with open(args.json, "w") as f:
            json.dump(rows, f, indent=2)
        print(f"wrote {args.json}")

    print(f"{'ch':>3} {'n':>4} {'real_exact':>10} {'real_ci':>8} {'neu_exact':>10} {'neu_ci':>8}")
    for r in rows:
        ne = f"{r['neu_exact']:.2f}" if r["neu_exact"] is not None else "  -  "
        nc = f"{r['neu_ci']:.2f}" if r["neu_ci"] is not None else "  -  "
        print(f"{r['ch']:>3} {r['n']:>4} {r['real_exact']:>10.2f} {r['real_ci']:>8.2f} "
             f"{ne:>10} {nc:>8}")

    common = [r for r in rows if r["n"] >= 100]
    rare = [r for r in rows if r["n"] < 10]
    print("\n--- rollup ---")
    print(f"REAL ink overall exact-match accuracy: {_avg(rows,'real_exact'):.2f} "
         f"(ceiling: how good OCR is on genuine handwriting to begin with)")
    print(f"NEURAL, common classes (n>=100, {len(common)} classes): "
         f"exact={_avg(common,'neu_exact'):.2f} case-insensitive={_avg(common,'neu_ci'):.2f}")
    print(f"NEURAL, rare classes   (n<10,  {len(rare)} classes): "
         f"exact={_avg(rare,'neu_exact'):.2f} case-insensitive={_avg(rare,'neu_ci'):.2f}")


if __name__ == "__main__":
    main()
